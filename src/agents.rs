//! AI coding agents and the signatures they leave in commits.
//!
//! Every rule is a *public, self-declared* signal: a co-author trailer, a bot
//! account or a footer the tool writes on its own. Code style is never used.

/// One identity matcher. All comparisons are ASCII case-insensitive.
enum Rule {
    /// "Name <email>" contains this.
    Contains(&'static str),
    /// "Name <email>" starts with this.
    Prefix(&'static str),
}

pub struct Agent {
    pub name: &'static str,
    identity: &'static [Rule],
    /// The commit message contains one of these (footers).
    message: &'static [&'static str],
}

use Rule::*;

