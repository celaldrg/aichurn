/// Returns the index into [`AGENTS`] of the first agent that signed this
/// commit, given its author, committer, co-author trailers and full message.
pub fn detect(identities: &[String], message: &str) -> Option<usize> {
    let ids: Vec<String> = identities.iter().map(|s| s.trim().to_ascii_lowercase()).collect();
    let msg = format!("\n{}", message.to_ascii_lowercase());
    for (i, a) in AGENTS.iter().enumerate() {
        for id in &ids {
            for r in a.identity {
                let hit = match r {
                    Contains(s) => id.contains(s),
                    Prefix(s) => id.starts_with(s),
                };
                if hit {
                    return Some(i);
                }
            }
        }
        if a.message.iter().any(|m| msg.contains(m)) {
            return Some(i);
        }
    }
    None
}

/// Plain automation (dependency bots, release and codegen bots). Their
/// commits are replayed but not counted, so "human" means people.
pub fn is_automation(author: &str) -> bool {
    let a = author.to_ascii_lowercase();
    ["[bot]", "dependabot", "renovate", "github-actions", "pre-commit-ci", "semantic-release", "greenkeeper", "snyk-bot"].iter().any(|b| a.contains(b))
}

/// Extracts the values of `Co-authored-by:` trailers from a commit message.
pub fn coauthors(message: &str) -> Vec<String> {
    message
        .lines()
        .filter_map(|l| {
            let l = l.trim();
            let (k, v) = l.split_once(':')?;
            k.trim().eq_ignore_ascii_case("co-authored-by").then(|| v.trim().to_string())
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn name(ids: &[&str], msg: &str) -> Option<&'static str> {
        let ids: Vec<String> = ids.iter().map(|s| s.to_string()).collect();
        detect(&ids, msg).map(|i| AGENTS[i].name)
    }

    #[test]
    fn detects_trailers_and_footers() {
        assert_eq!(name(&["Ada <ada@x.dev>", "Claude <noreply@anthropic.com>"], ""), Some("Claude Code"));
        assert_eq!(name(&["Ada <ada@x.dev>"], "Fix\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"), Some("Claude Code"));
        assert_eq!(name(&["Cursor Agent <cursoragent@cursor.com>"], ""), Some("Cursor"));
        assert_eq!(name(&["Copilot <198982749+Copilot@users.noreply.github.com>"], ""), Some("Copilot"));
        assert_eq!(name(&["copilot-swe-agent[bot] <1+copilot-swe-agent[bot]@users.noreply.github.com>"], ""), Some("Copilot"));
        assert_eq!(name(&["Ada <a@x>"], "feat: x\n\naider: add parser"), Some("Aider"));
        assert_eq!(name(&["Ada (aider) <a@x>"], ""), Some("Aider"));
        assert_eq!(name(&["google-labs-jules[bot] <x@users.noreply.github.com>"], ""), Some("Jules"));
    }

    #[test]
    fn humans_named_like_agents_are_humans() {
        assert_eq!(name(&["Claude Monet <claude@monet.fr>"], ""), None);
        assert_eq!(name(&["Devin Smith <devin@x.dev>"], ""), None);
        assert_eq!(name(&["Jules Verne <jules@x.dev>"], "mention aider: in the middle of a line"), None);
        assert_eq!(name(&["dependabot[bot] <x@users.noreply.github.com>"], ""), None);
    }

    #[test]
    fn automation() {
        assert!(is_automation("dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>"));
        assert!(is_automation("opencode-agent[bot] <x@users.noreply.github.com>"));
        assert!(!is_automation("Ada Lovelace <ada@x.dev>"));
    }

    #[test]
    fn release_bots_named_like_tools_are_not_agents() {
        assert_eq!(name(&["opencode <opencode@sst.dev>"], "sync release versions for v2.1.4"), None);
    }

    #[test]
    fn parses_coauthors() {
        let m = "Fix bug\n\nCo-authored-by: A <a@x>\nco-authored-by:  Claude <noreply@anthropic.com> \nSigned-off-by: B <b@x>";
        assert_eq!(coauthors(m), vec!["A <a@x>".to_string(), "Claude <noreply@anthropic.com>".to_string()]);
    }
}
